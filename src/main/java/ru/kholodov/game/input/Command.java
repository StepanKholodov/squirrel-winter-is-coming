package ru.kholodov.game.input;

/**
 * Паттерн Command — общий интерфейс для всех команд.
 * Инкапсулирует запрос на выполнение действия как объект, который
 * {@link InputHandler} кладёт в очередь и позже исполняет в потоке игры.
 */
public interface Command {

    /** Выполнить инкапсулированное действие. */
    void execute();
}
